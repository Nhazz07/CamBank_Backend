
CREATE TABLE bank_branches (
    branch_id   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    branch_code VARCHAR(20)                               NOT NULL,
    branch_name VARCHAR(100)                              NOT NULL,
    address     VARCHAR(300)                              NOT NULL,
    phone       VARCHAR(30),
    email       VARCHAR(255),
    status      VARCHAR(20) DEFAULT 'ACTIVE'              NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE                  NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE                  NOT NULL,
    CONSTRAINT pk_bank_branches PRIMARY KEY (branch_id),
    CONSTRAINT uq_bank_branches_code UNIQUE (branch_code)
);

CREATE TABLE users (
    user_id       NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email         VARCHAR(255)                                NOT NULL,
    password_hash VARCHAR(255)                                NOT NULL,
    status        VARCHAR(20) DEFAULT 'ACTIVE'                NOT NULL,
    last_login_at TIMESTAMP WITH TIME ZONE                    NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE                    NOT NULL,
    CONSTRAINT    pk_users PRIMARY KEY (user_id),
    CONSTRAINT    uq_users_email UNIQUE (email)
);

CREATE TABLE roles (
    role_id     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    role_code   VARCHAR2(30)                                NOT NULL,
    role_name   VARCHAR2(100)                               NOT NULL,
    description VARCHAR2(300),
    created_at  TIMESTAMP WITH TIME ZONE                    NOT NULL,
    CONSTRAINT pk_roles PRIMARY KEY (role_id),
    CONSTRAINT uq_roles_code UNIQUE (role_code)
);

CREATE TABLE user_roles (
    user_id     NUMBER(19)               NOT NULL,
    role_id     NUMBER(19)               NOT NULL,
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    assigned_by NUMBER(19),
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (role_id),
    CONSTRAINT fk_user_roles_assigned_by FOREIGN KEY (assigned_by) REFERENCES users (user_id)
);

