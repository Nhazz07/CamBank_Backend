-- Section 3: Employee Management & Section 4: Customer Management

CREATE TABLE employees (
                           employee_id       NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                           user_id           NUMBER(19)                                  NOT NULL,
                           employee_number   VARCHAR2(30)                                NOT NULL,
                           first_name        VARCHAR2(100)                               NOT NULL,
                           last_name         VARCHAR2(100)                               NOT NULL,
                           job_title         VARCHAR2(100)                               NOT NULL,
                           phone             VARCHAR2(30),
                           employment_status VARCHAR2(20) DEFAULT 'ACTIVE'               NOT NULL,
                           hired_at          TIMESTAMP WITH TIME ZONE                    NOT NULL,
                           created_at        TIMESTAMP WITH TIME ZONE                    NOT NULL,
                           updated_at        TIMESTAMP WITH TIME ZONE                    NOT NULL,
                           CONSTRAINT pk_employees PRIMARY KEY (employee_id),
                           CONSTRAINT uq_employees_user_id UNIQUE (user_id),
                           CONSTRAINT uq_employees_number UNIQUE (employee_number),
                           CONSTRAINT fk_employees_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE staff_branch_assignments (
                                          assignment_id  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                                          employee_id    NUMBER(19)                                  NOT NULL,
                                          branch_id      NUMBER(19)                                  NOT NULL,
                                          is_primary     BOOLEAN DEFAULT FALSE                       NOT NULL,
                                          assigned_from  TIMESTAMP WITH TIME ZONE                    NOT NULL,
                                          assigned_until TIMESTAMP WITH TIME ZONE,
                                          created_at     TIMESTAMP WITH TIME ZONE                    NOT NULL,
                                          CONSTRAINT pk_staff_branch_assignments PRIMARY KEY (assignment_id),
                                          CONSTRAINT uq_staff_branch_emp_branch_from UNIQUE (employee_id, branch_id, assigned_from),
                                          CONSTRAINT fk_sba_employee FOREIGN KEY (employee_id) REFERENCES employees (employee_id),
                                          CONSTRAINT fk_sba_branch FOREIGN KEY (branch_id) REFERENCES bank_branches (branch_id)
);

CREATE INDEX idx_sba_branch_id ON staff_branch_assignments (branch_id);

CREATE TABLE customers (
                           customer_id     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                           user_id         NUMBER(19),
                           customer_number VARCHAR2(30)                                NOT NULL,
                           first_name      VARCHAR2(100)                               NOT NULL,
                           last_name       VARCHAR2(100)                               NOT NULL,
                           date_of_birth   DATE,
                           email           VARCHAR2(255),
                           phone           VARCHAR2(30)                                NOT NULL,
                           address         VARCHAR2(300),
                           status          VARCHAR2(20) DEFAULT 'ACTIVE'               NOT NULL,
                           created_at      TIMESTAMP WITH TIME ZONE                    NOT NULL,
                           updated_at      TIMESTAMP WITH TIME ZONE                    NOT NULL,
                           CONSTRAINT pk_customers PRIMARY KEY (customer_id),
                           CONSTRAINT uq_customers_user_id UNIQUE (user_id),
                           CONSTRAINT uq_customers_number UNIQUE (customer_number),
                           CONSTRAINT fk_customers_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE INDEX idx_customers_phone ON customers (phone);
CREATE INDEX idx_customers_last_name ON customers (last_name);